import { FacilityCalculationScenario } from './facility-calculation.types';

interface HelpTerm {
  term: string;
  definition: string;
}

const surplus: HelpTerm = {
  term: 'Surplus gained (tCO₂e)',
  definition: 'the total amount of over-performance resulting from the current report submission.',
};
const removed: HelpTerm = {
  term: 'Previous surplus gained/removed (tCO₂e)',
  definition:
    'where applicable, the amount of surplus generated from the previous report submission. This amount will be deducted from the existing surplus balance.',
};
const amount: HelpTerm = {
  term: 'Amount above target (tCO₂e)',
  definition: 'the total amount of under-performance resulting from the current report submission.',
};
const cost: HelpTerm = {
  term: 'Cost (GBP / tCO₂e)',
  definition: 'the target period-specific buy-out fee rate applied',
};
const total: HelpTerm = {
  term: 'Total buy-out fee (GBP)',
  definition:
    'the total amount of buy-out fee due for the current under-performance (before considering any buy-out fee already paid for this facility from previous report submissions).',
};
const paid: HelpTerm = {
  term: 'Previous buy-out fee received (GBP)',
  definition: 'where applicable, the amount of buy-out fee payment received for the previous under-performance.',
};
const rebanked: HelpTerm = {
  term: 'Previous surplus used/re-banked (tCO₂e)',
  definition:
    'where applicable, the amount of surplus that was previously used to offset the under-performance in the primary report submission. This amount of surplus has been credited back to the facility and can be used to offset under-performance for a future target period report.',
};
const overpayment: HelpTerm = {
  term: 'Overpayment buy-out amount (GBP)',
  definition:
    'the amount of buy-out fee payment received for a previous under-performance that has resulted in an overpayment. The operator has been invited to claim this amount back from DESNZ through the refund letter generated by this process.',
};
const refundTransaction: HelpTerm = {
  term: 'Refund transaction ID',
  definition:
    'the unique reference ID associated with the refund of an overpaid buy-out fee from a previous under-performance. This allows the refund status to be tracked in MyCCA.',
};

export function facilityCalculationHelp(
  scenario: FacilityCalculationScenario,
): { summary: string; terms: HelpTerm[] } | undefined {
  switch (scenario) {
    case 'secondary-surplus':
      return {
        summary: 'I need help with the surplus terms',
        terms: [
          surplus,
          {
            ...removed,
            definition:
              'where applicable, the amount of surplus generated from the previous report submission. This amount will be deducted from the existing surplus balance and, where applicable, replaced with the surplus calculated from the current report submission.',
          },
        ],
      };
    case 'secondary-buyout-after-buyout':
    case 'secondary-buyout-after-surplus':
      return {
        summary: 'I need help with the buy-out terms',
        terms: [
          amount,
          cost,
          total,
          paid,
          rebanked,
          {
            term: 'Secondary buy-out fee (GBP)',
            definition:
              'the net amount of buy-out fee due for the current under-performance (after considering any buy-out fee already paid for this facility from previous report submissions).',
          },
          removed,
          { term: 'Transaction ID', definition: 'the unique reference ID for the buy-out fee notice issued' },
        ],
      };
    case 'secondary-target-met-refund':
      return {
        summary: 'I need help with the refund terms',
        terms: [
          surplus,
          paid,
          {
            ...rebanked,
            definition:
              'where applicable, the amount of surplus used to offset the primary under-performance. This surplus amount has been credited back to the facility and may be available for use in a future target period.',
          },
          overpayment,
          refundTransaction,
        ],
      };
    case 'secondary-target-not-met-refund':
      return {
        summary: 'I need help with the refund terms',
        terms: [amount, cost, total, paid, rebanked, overpayment, refundTransaction],
      };
    default:
      return undefined;
  }
}
